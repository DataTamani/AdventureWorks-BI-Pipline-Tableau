COPY INTO RAW_PRODUCTS
FROM @ADW_DB.ADW_RAW.ADW_STAGE/AdventureWorks_Products.csv
FILE_FORMAT = (FORMAT_NAME = ADW_CSV_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_TERRITORIES
FROM @ADW_DB.ADW_RAW.ADW_STAGE/AdventureWorks_Territories.csv
FILE_FORMAT = (FORMAT_NAME = ADW_CSV_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_CUSTOMERS
FROM @ADW_DB.ADW_RAW.ADW_STAGE/AdventureWorks_Customers.csv
FILE_FORMAT = (FORMAT_NAME = ADW_CSV_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';


