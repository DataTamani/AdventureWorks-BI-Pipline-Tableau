LIST @ADW_DB.ADW_RAW.ADW_STAGE;


-- Chargement des 8 fichiers CSV AdventureWorks 

USE WAREHOUSE ADW_WH;
USE DATABASE  ADW_DB;
USE SCHEMA    ADW_RAW;


CREATE OR REPLACE FILE FORMAT ADW_CSV_FORMAT
    TYPE = CSV
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    DATE_FORMAT = 'MM/DD/YYYY'
    ENCODING = 'ISO-8859-1'
    NULL_IF = ('', 'NULL', 'NA')
    EMPTY_FIELD_AS_NULL = TRUE
    TRIM_SPACE = FALSE;


-- 1. VALIDATION sur les 3 CSV ventes (ne charge rien)

COPY INTO RAW_SALES_2015
FROM @ADW_DB.ADW_RAW.ADW_STAGE/AdventureWorks_Sales_2015.csv
FILE_FORMAT = (FORMAT_NAME = ADW_CSV_FORMAT)
VALIDATION_MODE = 'RETURN_ERRORS';

COPY INTO RAW_SALES_2016
FROM @ADW_DB.ADW_RAW.ADW_STAGE/AdventureWorks_Sales_2016.csv
FILE_FORMAT = (FORMAT_NAME = ADW_CSV_FORMAT)
VALIDATION_MODE = 'RETURN_ERRORS';

COPY INTO RAW_SALES_2017
FROM @ADW_DB.ADW_RAW.ADW_STAGE/AdventureWorks_Sales_2017.csv
FILE_FORMAT = (FORMAT_NAME = ADW_CSV_FORMAT)
VALIDATION_MODE = 'RETURN_ERRORS';

-- 2. COPY INTO réels — DIMENSIONS

COPY INTO RAW_CATEGORIES
FROM @ADW_DB.ADW_RAW.ADW_STAGE/AdventureWorks_Product_Categories.csv
