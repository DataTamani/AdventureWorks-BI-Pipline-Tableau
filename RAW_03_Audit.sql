
-- Audit de la couche RAW 

USE WAREHOUSE ADW_WH;
USE DATABASE  ADW_DB;
USE SCHEMA    ADW_RAW;


-- 1. AUDIT DES VOLUMES 

SELECT 'RAW_CATEGORIES'    AS TABLE_NAME, COUNT(*) AS NB_LIGNES FROM RAW_CATEGORIES
UNION ALL SELECT 'RAW_SUBCATEGORIES', COUNT(*) FROM RAW_SUBCATEGORIES
UNION ALL SELECT 'RAW_PRODUCTS',      COUNT(*) FROM RAW_PRODUCTS
UNION ALL SELECT 'RAW_TERRITORIES',   COUNT(*) FROM RAW_TERRITORIES
UNION ALL SELECT 'RAW_CUSTOMERS',     COUNT(*) FROM RAW_CUSTOMERS
UNION ALL SELECT 'RAW_SALES_2015',    COUNT(*) FROM RAW_SALES_2015
UNION ALL SELECT 'RAW_SALES_2016',    COUNT(*) FROM RAW_SALES_2016
UNION ALL SELECT 'RAW_SALES_2017',    COUNT(*) FROM RAW_SALES_2017
ORDER BY TABLE_NAME;


-- 2. AUDIT DES VALEURS NULLES (Clés primaires manquantes)

SELECT 
    'RAW_PRODUCTS ProductKey NULL' AS CONTROLE, 
    COUNT(*) AS NB_ERREURS 
FROM RAW_PRODUCTS WHERE ProductKey IS NULL
UNION ALL
SELECT 'RAW_CUSTOMERS CustomerKey NULL', COUNT(*) 
FROM RAW_CUSTOMERS WHERE CustomerKey IS NULL
UNION ALL
SELECT 'RAW_TERRITORIES SalesTerritoryKey NULL', COUNT(*) 
FROM RAW_TERRITORIES WHERE SalesTerritoryKey IS NULL
UNION ALL
SELECT 'RAW_SALES_2015 OrderNumber NULL', COUNT(*) 
FROM RAW_SALES_2015 WHERE OrderNumber IS NULL
UNION ALL
SELECT 'RAW_SALES_2016 OrderNumber NULL', COUNT(*) 
FROM RAW_SALES_2016 WHERE OrderNumber IS NULL
UNION ALL
SELECT 'RAW_SALES_2017 OrderNumber NULL', COUNT(*) 
FROM RAW_SALES_2017 WHERE OrderNumber IS NULL;


-- 3. AUDIT DES DOUBLONS (Clés primaires en double)

SELECT 'RAW_PRODUCTS Doublons' AS CONTROLE, COUNT(*) AS NB_ERREURS
FROM (SELECT ProductKey FROM RAW_PRODUCTS GROUP BY ProductKey HAVING COUNT(*) > 1)
UNION ALL
SELECT 'RAW_CUSTOMERS Doublons', COUNT(*)
FROM (SELECT CustomerKey FROM RAW_CUSTOMERS GROUP BY CustomerKey HAVING COUNT(*) > 1)
UNION ALL
SELECT 'RAW_CATEGORIES Doublons', COUNT(*)
FROM (SELECT ProductCategoryKey FROM RAW_CATEGORIES GROUP BY ProductCategoryKey HAVING COUNT(*) > 1);


-- 4. AUDIT DES DATES (Intégrité temporelle sur les ventes)

SELECT 
    'Dates invalides (NULL)' AS CONTROLE, COUNT(*) AS NB_ERREURS 
FROM RAW_SALES_2015 WHERE OrderDate IS NULL OR StockDate IS NULL
UNION ALL
SELECT 'Dates invalides (NULL)', COUNT(*) 
FROM RAW_SALES_2016 WHERE OrderDate IS NULL OR StockDate IS NULL
UNION ALL
SELECT 'Dates invalides (NULL)', COUNT(*) 
FROM RAW_SALES_2017 WHERE OrderDate IS NULL OR StockDate IS NULL;